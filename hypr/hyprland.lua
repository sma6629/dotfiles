-- See https://wiki.hypr.land/Configuring/Basics/Binds/ for more
local mainMod  = "SUPER" -- Sets "Windows" key as main modifier
local screenshot_dir = "~/Pictures/Screenshots/"

hl.bind(mainMod .. " + RETURN", hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + Q", hl.dsp.window.close())
hl.bind(mainMod .. " + M", hl.dsp.exit())
hl.bind(mainMod .. " + E", hl.dsp.exec_cmd(fileManager))
hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + W", hl.dsp.exec_cmd(menu))
hl.bind(mainMod .. " + P", hl.dsp.window.pseudo()) -- dwindle
-- hl.bind(mainMod .. " + O", hl.dsp.layout("togglesplit")) -- dwindle
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen({ mode = "fullscreen", action = "toggle" })) -- full fullscreen
hl.bind(mainMod .. " + SHIFT + F", hl.dsp.window.fullscreen({ mode = "maximized", action = "toggle" })) -- maximize (keeps gaps/padding)
hl.bind(mainMod .. " + R", hl.dsp.exec_cmd("pkill Hyprland"))

-- Move focus with mainMod + arrow keys
hl.bind(mainMod .. " + left",  hl.dsp.focus({ direction = "l" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "r" }))
hl.bind(mainMod .. " + up",    hl.dsp.focus({ direction = "u" }))
hl.bind(mainMod .. " + down",  hl.dsp.focus({ direction = "d" }))

-- Move focus with mainMod + vim keys
hl.bind(mainMod .. " + H", hl.dsp.focus({ direction = "l" }))
hl.bind(mainMod .. " + L", hl.dsp.focus({ direction = "r" }))
hl.bind(mainMod .. " + K", hl.dsp.focus({ direction = "u" }))
hl.bind(mainMod .. " + J", hl.dsp.focus({ direction = "d" }))

-- Switch workspaces with mainMod + [0-9]
-- Move active window to a workspace with mainMod + SHIFT + [0-9]
for i = 1, 10 do
    local key = i % 10 -- 10 maps to key 0
    hl.bind(mainMod .. " + " .. key,         hl.dsp.focus({ workspace = i }))
    hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Switch workspaces with SUPER + CTRL + arrow keys
hl.bind(mainMod .. " + CTRL + left",  hl.dsp.focus({ workspace = "r-1" })) -- Move to workspace on the left
hl.bind(mainMod .. " + CTRL + right", hl.dsp.focus({ workspace = "r+1" })) -- Move to workspace on the right

-- switch between most recent workspaces
hl.config({
    binds = {
        allow_workspace_cycles = true,
    },
})
hl.bind(mainMod .. " + Tab", hl.dsp.focus({ workspace = "previous" }))

-- hyprlock
hl.bind(mainMod .. " + SHIFT + l", hl.dsp.exec_cmd("hyprlock"))

-- hyprshot
hl.bind("Print",          hl.dsp.exec_cmd("hyprshot -m output -o " .. screenshot_dir)) -- Full screen
hl.bind("SHIFT + Print",  hl.dsp.exec_cmd("hyprshot -m region -o " .. screenshot_dir)) -- Select area
hl.bind("ALT + Print",    hl.dsp.exec_cmd("hyprshot -m window -o" .. screenshot_dir))    -- Active window

-- Example special workspace (scratchpad)
hl.bind(mainMod .. " + S",         hl.dsp.workspace.toggle_special("magic"))
hl.bind(mainMod .. " + SHIFT + S", hl.dsp.window.move({ workspace = "special:magic" }))

-- Scroll through existing workspaces with mainMod + scroll
hl.bind(mainMod .. " + mouse_down", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(mainMod .. " + mouse_up",   hl.dsp.focus({ workspace = "e-1" }))

-- Move/resize windows with mainMod + LMB/RMB and dragging
hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(),   { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })

