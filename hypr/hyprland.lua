-- exec-once equivalent: starts the session stack once on session start
hl.on("hyprland.start", function()
    hl.exec_cmd("hyprpaper & waybar & swaync & hypridle")
end)

-- exec equivalent: restart any missing processes after a config reload
-- (hyprland.start only fires once, so this lives on config.reloaded instead)
hl.on("config.reloaded", function()
    hl.exec_cmd("pgrep waybar || waybar")
    hl.exec_cmd("pgrep hypridle || hypridle")
    hl.exec_cmd("pgrep hyprpaper || hyprpaper")
end)

